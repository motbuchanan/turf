# Bosses, items and a fight cut short (v0.4.1): make items at the Corner Store, drop a boss and use its move, cast an item,
# close the app mid-fight and check the fight is counted exactly once on the next start, then watch it from Your fights.
import os, json
from playwright.sync_api import sync_playwright
URL = os.environ.get('TURF_URL', 'http://localhost:8123/index.html')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'proof', ''); os.makedirs(OUT, exist_ok=True)
blk = [dict(key='b1',k='house',x=13,y=12,lv=2), dict(key='b2',k='gym',x=10,y=9,lv=3), dict(key='b3',k='pad',x=17,y=9,lv=2), dict(key='b4',k='stash',x=10,y=15,lv=2),
       dict(key='b5',k='supstash',x=17,y=15,lv=2), dict(key='b6',k='store',x=12,y=17,lv=1)]
save = dict(v=1, rescued=True, reports=[], block=blk, cash=900, sup=900, color='teal', army=dict(brawler=12, shooter=8, bruiser=1), nk=40, rep=0)
ok = True
def check(n, c, x=''):
    global ok; print(('PASS ' if c else 'FAIL ') + n, x, flush=True); ok = ok and bool(c)
with sync_playwright() as p:
    b = p.chromium.launch(args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    pg = b.new_page(viewport=dict(width=844, height=390), device_scale_factor=2); errs = []
    pg.add_init_script("try{localStorage.setItem('turf.intro.v1','1')}catch(e){}")   # these proofs skip the intro
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(URL); pg.wait_for_timeout(600); pg.evaluate("s => localStorage.setItem('turf.save.v1', s)", json.dumps(save)); pg.reload(); pg.wait_for_timeout(1800)
    sv = lambda: pg.evaluate("JSON.parse(localStorage.getItem('turf.save.v1'))")
    pg.click('#goBtn'); pg.wait_for_timeout(900)
    pg.click('#hCrew'); pg.wait_for_timeout(400)
    txt = pg.locator('#sheetBody').inner_text()
    check('crew sheet lists the three bosses', all(n in txt for n in ['The Enforcer', 'Deadeye', 'The Shot Caller']))
    check('items show, with the Corner Store holding 2', 'Items' in txt and '0 of 2' in txt, txt[-300:])
    pg.click('[data-make="hype"]'); pg.wait_for_timeout(300); pg.click('[data-make="firecracker"]'); pg.wait_for_timeout(300); pg.click('[data-make="firstaid"]'); pg.wait_for_timeout(300)
    s = sv(); check('two items made, the third refused for room', s['kit'] == {'hype':1, 'firecracker':1} and s['sup'] == 900 - 120 - 150, str(s['kit']) + ' ' + str(s['sup']))
    check('Ladder waits for a higher Corner Store', pg.locator('[data-make="ladder"]').count() == 0)
    pg.click('#sheetX'); pg.wait_for_timeout(200); pg.click('#hAttack'); pg.wait_for_timeout(400)
    pg.locator('.blk').nth(0).scroll_into_view_if_needed(); pg.locator('.blk').nth(0).click(); pg.wait_for_timeout(1500)
    keys = pg.evaluate("[...document.querySelectorAll('#bar .troop')].map(b => b.dataset.k)")
    check('bar: fighters first, then bosses, then items', keys[:3] == ['brawler', 'shooter', 'bruiser'] and keys[3:6] == ['b:enforcer', 'b:deadeye', 'b:shotcaller'] and keys[-2:] == ['i:hype', 'i:firecracker'], str(keys))
    def drop(k, x, y):
        pg.click('.troop[data-k="%s"]' % k); q = pg.evaluate(f'TURF_TEST.toScreen({x},{y})'); pg.mouse.click(q[0], q[1]); pg.wait_for_timeout(70)
    drop('b:enforcer', 14.5, 23.3); pg.wait_for_timeout(1500)
    check('the Enforcer card turns into Lights Out', pg.inner_text('.troop[data-k="b:enforcer"] .nm') == 'Lights Out' and 'ready' in pg.get_attribute('.troop[data-k="b:enforcer"]', 'class'))
    for n in range(10): drop('brawler', 12.6 + n * .4, 23.5)
    drop('b:shotcaller', 15, 23.6)
    for n in range(8): drop('shooter', 13 + n * .4, 24.1)
    drop('bruiser', 14, 23.2)
    sel = pg.evaluate('TURF_TEST.state()')['sel']; check('after a drop the next pick is never an item', not (sel or '').startswith('i:'), str(sel))
    pg.wait_for_timeout(2500); pg.click('.troop[data-k="b:enforcer"]'); pg.wait_for_timeout(300)
    check('Lights Out is used once', 'out' in pg.get_attribute('.troop[data-k="b:enforcer"]', 'class'))
    drop('i:hype', 14.5, 19.5); pg.wait_for_timeout(1500)
    check('Hype Track is cast and its card is used up', 'out' in pg.get_attribute('.troop[data-k="i:hype"]', 'class'))
    pg.screenshot(path=OUT + 'turf-v0.4.1-hype.png')
    pg.wait_for_timeout(3000)
    pend = pg.evaluate("JSON.parse(localStorage.getItem('turf.pending.v1'))"); check('the fight in progress is saved under its own key', pend is not None and any(d.get('c') == 'hype' for d in pend['recipe']['deploys']) and 'pending' not in sv(), str((pend or {}).get('recipe', {}).get('deploys', [])[-3:]))
    pg.reload(); pg.wait_for_timeout(2500)
    s = sv(); rec = s['camp'].get('0-0')
    check('after closing mid-fight, the fight is counted on the next start', pg.evaluate("localStorage.getItem('turf.pending.v1')") is None and len(s['reports']) == 1 and s['tries'] == 1 and rec is not None, str(rec))
    check('the item used in it is gone, the one not used is kept', s['kit'] == {'firecracker':1}, str(s['kit']))
    rr = s['reports'][0]['recipe']; landed = [rr['attackers'][d['i']]['type'] for d in rr['deploys'] if 'i' in d and 'ab' not in d]
    check('exactly the fighters that went in are spent', all(s['army'][k] == save['army'].get(k, 0) - sum(1 for t in landed if t == k) for k in ('brawler', 'shooter', 'bruiser')) and len(landed) >= 14, str(s['army']) + ' landed ' + str(len(landed)))
    pg.reload(); pg.wait_for_timeout(2000); s2 = sv()
    check('it is counted only once', len(s2['reports']) == 1 and s2['tries'] == 1 and s2['cash'] == s['cash'])
    pg.click('#goBtn'); pg.wait_for_timeout(900); pg.click('#hAttack'); pg.wait_for_timeout(400); pg.click('[data-act="fights"]'); pg.wait_for_timeout(400)
    t = pg.locator('#sheetBody').inner_text(); check('Your fights lists it', 'Boombox Kings, block 1, day' in t, t[:200])
    pg.click('[data-watch="0"]'); pg.wait_for_timeout(2500)
    check('Watch replays it', pg.evaluate('TURF_TEST.state()')['screen'] == 'watch')
    pg.screenshot(path=OUT + 'turf-v0.4.1-watch.png')
    pg.click('#wSkip'); pg.wait_for_timeout(2500)
    if pg.evaluate('TURF_TEST.state()')['screen'] == 'watch': pg.wait_for_timeout(5000)
    check('a replay from Your fights goes back to the list', pg.evaluate('TURF_TEST.state()')['screen'] == 'home' and pg.evaluate('TURF_TEST.home()')['sheet'] == 'fights')
    pg.evaluate("TURF_TEST.hit(-1, 0)"); pg.wait_for_timeout(1500)
    keys = pg.evaluate("[...document.querySelectorAll('#bar .troop')].map(b => b.dataset.k)"); check('bosses sit out the Boombox corner', not any(k.startswith('b:') for k in keys), str(keys))
    c0 = sv()['cash']; pg.click('#endBtn'); pg.wait_for_timeout(2500)
    check('pressing End before anyone goes in pays nothing', sv()['cash'] == c0, str(c0) + ' -> ' + str(sv()['cash']))
    check('no console errors', not errs, str(errs[:3]))
    b.close()
print('BOSSES', 'PASS' if ok else 'FAIL')
